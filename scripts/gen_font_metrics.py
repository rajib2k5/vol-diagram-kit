"""Regenerate diagram_kit/_font_metrics.py from the bundled TTF files.

Dev-only (needs fontTools from the dev dependency group):

    uv run python scripts/gen_font_metrics.py

The generated table lets the layout measure text without fontTools at
runtime, and makes the measurement identical on every machine.
"""

from __future__ import annotations

from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "diagram_kit" / "fonts"
OUT = ROOT / "diagram_kit" / "_font_metrics.py"

# Printable ASCII, Latin-1 supplement, and a few typographic / math extras
# that show up in quant diagrams.
CODEPOINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [ord(c) for c in "–—‘’“”•…→←↑↓↔⇒×·≤≥≈≠±σμΔΣβθλρτνω√∞€"]
)


def advances(path: Path) -> dict[int, int]:
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    out: dict[int, int] = {}
    for cp in CODEPOINTS:
        glyph = cmap.get(cp)
        if glyph is None:
            continue
        out[cp] = hmtx[glyph][0]
    return out


def main() -> None:
    regular = FONTS / "LiberationSans-Regular.ttf"
    bold = FONTS / "LiberationSans-Bold.ttf"
    reg = advances(regular)
    bld = advances(bold)
    common = sorted(set(reg) & set(bld))
    head = TTFont(regular)
    upm = head["head"].unitsPerEm
    os2 = head["OS/2"]
    lines = [
        '"""Generated by scripts/gen_font_metrics.py from the bundled Liberation Sans 2.1.5. Do not edit."""',
        "",
        f"UNITS_PER_EM = {upm}",
        f"CAP_HEIGHT = {os2.sCapHeight}",
        f"X_HEIGHT = {os2.sxHeight}",
        "",
        "REGULAR = {",
    ]
    lines += [f"    {cp}: {reg[cp]}," for cp in common]
    lines += ["}", "", "BOLD = {"]
    lines += [f"    {cp}: {bld[cp]}," for cp in common]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    missing = [chr(cp) for cp in CODEPOINTS if cp not in common]
    print(f"wrote {OUT} ({len(common)} glyphs); not in font: {''.join(missing)!r}")


if __name__ == "__main__":
    main()
