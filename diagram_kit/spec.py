    """``child.child_col`` references ``parent.parent_col``.

    ``cardinality`` is how many child rows exist per parent row. The parent end
    is "exactly one", or "zero or one" when the child column is nullable.
    """

    child: str
    child_col: str
    parent: str
    parent_col: str
    cardinality: str
    label: str | None
    parent_optional: bool
    implicit: bool


