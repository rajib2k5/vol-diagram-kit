class FlowSpec:
    name: str
    title: str
    subtitle: str | None
    direction: str
    lanes: tuple[Lane, ...]
    nodes: tuple[Node, ...]
    edges: tuple[Edge, ...]
    legend: bool
    # (edge style, legend text) the spec names; other styles keep their default text
    edge_legend: tuple[tuple[str, str], ...] = ()
    kind: str = "flow"


@dataclass(frozen=True)
class Column:
    name: str
    type: str
    pk: bool
    fk: tuple[str, str] | None
    nullable: bool


@dataclass(frozen=True)
class Entity:
    id: str
    label: str
    columns: tuple[Column, ...]

    def column_index(self, name: str) -> int:
        for i, col in enumerate(self.columns):
            if col.name == name:
                return i
        raise KeyError(name)


