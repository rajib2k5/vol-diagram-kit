"""YAML spec loading and validation.

Every problem found in a spec is collected and reported together, each with a
path such as ``edges[3].to`` so the offending line is easy to find.
"""

from __future__ import annotations

import difflib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Union

import yaml

from .textmetrics import unsupported_chars

ID_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Mermaid erDiagram attribute types: letters, digits, _ - [ ] ( ) only.
COLUMN_TYPE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_\-\[\]\(\)]*$")
NODE_TYPES = ("source", "store", "process", "model", "output", "external", "ui")
EDGE_STYLES = ("data", "control", "dashed")
DIRECTIONS = ("LR", "TB")
MESSAGE_KINDS = ("sync", "async", "return")
CARDINALITIES = ("0..1", "1..1", "0..*", "1..*")
KINDS = ("flow", "erd", "sequence")
# Ids Mermaid cannot take, per position. Generated by scripts/gen_mermaid_reserved.py,
# which puts every candidate (Mermaid keywords of every grammar, JavaScript
# property names) in every position in three casings and renders the kit's own
# output with Mermaid 12.2.0 (GitHub) and 11.17.2 (mermaid-cli): a word that
# failed in all three casings is rejected in any case, otherwise only the
# spellings that failed.
RESERVED_FILE = Path(__file__).resolve().parent / "mermaid_reserved.json"
POSITION_DIAGRAM = {"flow_node": "flowchart", "flow_lane": "flowchart", "erd_entity": "erDiagram",
                    "erd_colname": "erDiagram", "erd_coltype": "erDiagram", "seq_participant": "sequenceDiagram"}


def load_reserved(path: Path = RESERVED_FILE) -> dict[str, tuple[frozenset[str], frozenset[str]]]:
    """Position -> (words rejected in any case, spellings rejected exactly)."""
    data = json.loads(path.read_text(encoding="utf-8"))
    return {pos: (frozenset(v["reject_any_case"]), frozenset(v["reject_exact"])) for pos, v in data["positions"].items()}


RESERVED = load_reserved()


# Mermaid picks the diagram type with /^\s*C4Context|C4Container|C4Component|C4Dynamic|C4Deployment/,
# unanchored after the first '|': an id containing one of those words turns the
# whole file into a C4 diagram (labels escape it; ids cannot).
C4_DETECTOR_RE = re.compile(r"C4(?:Container|Component|Dynamic|Deployment)")


def mermaid_reserved(pos: str, val: str) -> bool:
    any_case, exact = RESERVED[pos]
    return val.lower() in any_case or val in exact or C4_DETECTOR_RE.search(val) is not None


def suggest_id(val: str) -> str:
    """A rename the validator accepts in the same place (checked by scripts/gen_mermaid_reserved.py)."""
    if C4_DETECTOR_RE.search(val):
        return C4_DETECTOR_RE.sub(lambda m: "c4" + m.group()[2:], val)
    if ERD_MARKDOWN_ID_RE.match(val):
        core = val.strip("_")
        return core if ID_RE.match(core) else f"x{core}"
    return val + "_id"


# erDiagram lexes PK / FK / UK (any case) as key markers anywhere inside an
# entity's attribute block: a column named so, or a type that is one or starts
# with one followed by '-', '(' or '['.
ERD_ATTRIBUTE_KEYS = {"pk", "fk", "uk"}
ERD_KEY_TYPE_RE = re.compile(r"^(?i:pk|fk|uk)(?![A-Za-z0-9_])")
# erDiagram shows entity names, column names and types as Markdown: an id that
# starts and ends with '_' around a letter or digit loses those underscores
# (_id_ -> italic 'id', __x__ -> bold 'x').
ERD_MARKDOWN_ID_RE = re.compile(r"^_.*[A-Za-z0-9].*_$")
# Mermaid drops '<x...' from diagram titles as an HTML tag and prints any other '<' as '&lt;'.
TITLE_BAD_CHARS = "<"
# Mermaid's internal marker for ';': it replaces every '¶ß' in the finished SVG,
# so no escape shows it in a title, a flowchart or an erDiagram (sequence text
# can show it). Measured on 12.2.0 and 11.17.2.
SEMICOLON_MARKER = "¶ß"
MAX_BLOCK_DEPTH = 4
_SPACE_RUN = re.compile(" {2,}")


